# ============================================================
# NORMALIZE HEADING
# ============================================================

def normalize_heading(text):
    if not isinstance(text, str):
        return ""

    text = text.strip()
    
    # Remove common numbering
    text = re.sub(
        r"^(chapter\s*)?\d+[\.\):\-]?\s*",
        "",
        text,
        flags=re.IGNORECASE
    )

    text = re.sub(
        r"^[IVXLC]+[\.\):\-]\s*",
        "",
        text,
        flags=re.IGNORECASE
    )

    # Remove repeated spaces
    text = re.sub(r"\s+", " ", text)

    return text.strip()


# ============================================================
# CHECK WHETHER A LINE IS A REAL HEADING
# ============================================================

def is_heading(line):
    line = line.strip()

    if not line:
        return False

    # --------------------------------------------------
    # BASIC FILTERS
    # --------------------------------------------------

    if len(line) > 120:
        return False

    normalized = normalize_heading(line)
    upper = normalized.upper()

    # --------------------------------------------------
    # EXACT KNOWN HEADINGS
    # --------------------------------------------------

    if upper in KNOWN_HEADINGS:
        return True

    # --------------------------------------------------
    # OBVIOUS NON-HEADINGS / DOCUMENT GARBAGE
    # --------------------------------------------------

    if line.endswith((".", ",", ";", ":")):
        return False

    if len(line.split()) > 12:
        return False

    garbage_phrases = [
    "TABLE OF CONTENTS",
    "RED HERRING PROSPECTUS",
    "DISCLAIMER",
    "NA NA",
    "SD/-",
    "FORMERLY NAMED",
    "FORMERLY KNOWN",
]
    upper_line = line.upper()

    for phrase in garbage_phrases:
        if phrase in upper_line:
            return False

    # --------------------------------------------------
    # COMPANY-NAME FILTER
    # --------------------------------------------------

    company_indicators = [
        "PRIVATE LIMITED",
        "LIMITED",
        " LTD",
        "LTD.",
        "INC.",
        "CORPORATION",
        "CORP.",
    ]

    for indicator in company_indicators:
        if indicator in upper_line:
            return False

    # --------------------------------------------------
    # DATA / TABLE FILTER
    # --------------------------------------------------

    blocked_terms = [
        "CIN",
        "ISIN",
        "PAN",
        "GST",
        "EMAIL",
        "WEBSITE",
        "TELEPHONE",
        "PHONE",
        "FAX",
        "DATED",
        "DATE",
        "PAGE",
        "RS.",
        "₹",
        "%",
        "NIL",
    ]

    for term in blocked_terms:
        if term in upper_line:
            return False

    # --------------------------------------------------
    # NUMERIC / TABLE-ROW FILTER
    # --------------------------------------------------

    digit_count = sum(c.isdigit() for c in line)

    if digit_count >= 3:
        return False

    if "|" in line:
        return False

    # --------------------------------------------------
    # VERY SHORT / NOISY LINES
    # --------------------------------------------------

    letters = re.sub(r"[^A-Za-z]", "", line)

    if len(letters) < 5:
        return False

    # Single-word headings are allowed only when they
    # are already recognized as known headings.
    if len(line.split()) == 1:
        return False

    # --------------------------------------------------
    # ALL-CAPS HEADING DETECTION
    # --------------------------------------------------

    uppercase_letters = sum(
        1 for c in letters if c.isupper()
    )

    uppercase_ratio = (
        uppercase_letters / len(letters)
    )

    if uppercase_ratio >= 0.90:

        if len(line) <= 100 and len(line.split()) <= 10:

            # Avoid lines containing excessive symbols
            symbol_count = sum(
                1 for c in line
                if not c.isalnum() and not c.isspace()
            )

            if symbol_count > 8:
                return False

            return True

    return False
